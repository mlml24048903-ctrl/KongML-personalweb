const { chromium } = require("C:/Users/mlml2/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright");

(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe" });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  await page.addInitScript(() => localStorage.clear());
  await page.goto("http://127.0.0.1:4173/?view=felt-canvas-v2", { waitUntil: "networkidle" });
  await page.mouse.wheel(0, -180); await page.waitForTimeout(1100);
  await page.mouse.wheel(0, -180); await page.waitForTimeout(1100);
  await page.locator("body.message-board-open").waitFor();
  const tear = page.locator("#feltTearButton");
  await tear.click();
  await page.waitForTimeout(180);
  await page.screenshot({ path: "tests/felt-tear-origin-v3.png", fullPage: true });
  await page.locator("#feltEditor[open]").waitFor();
  const before = await page.locator("body").getAttribute("class");
  await page.locator("#feltEditor").hover(); await page.mouse.wheel(0, 900); await page.waitForTimeout(250);
  const after = await page.locator("body").getAttribute("class");
  if (!before.includes("message-board-open") || !after.includes("message-board-open")) throw new Error("editor wheel changed page mode");
  await page.locator("#feltTabImage").click();
  if (await page.locator("#feltImageField").isHidden()) throw new Error("image tab did not open");
  if (await page.locator("#feltImageClear").count()) throw new Error("remove image button remains");
  if (await page.locator("#feltImageDropzone").count() !== 1) throw new Error("image dropzone missing");
  await page.screenshot({ path: "tests/felt-editor-tabs-v3.png", fullPage: true });
  await page.locator("#feltTabMarkdown").focus(); await page.keyboard.press("ArrowRight");
  if ((await page.locator("#feltTabDoodle").getAttribute("aria-selected")) !== "true") throw new Error("tab keyboard navigation failed");
  await page.locator("#feltEditorCancel").click();
  await page.waitForTimeout(1400);
  if (await page.locator("#feltEditor[open]").count()) throw new Error("note editor opened without a new tear action");
  const canvasBox = await page.locator("#feltCanvas").boundingBox();
  const pinBox = await page.locator("#feltPinButton").boundingBox();
  await page.mouse.click(pinBox.x + 18, pinBox.y + 18);
  await page.mouse.click(canvasBox.x + canvasBox.width * .32, canvasBox.y + canvasBox.height * .59);
  await page.waitForTimeout(600);
  const notes = await page.evaluate(() => JSON.parse(localStorage.getItem("km-felt-canvas-notes-v1") || "[]"));
  if (notes.some(note => note.pinned === true)) throw new Error("legacy pin state remains");
  await page.mouse.dblclick(canvasBox.x + canvasBox.width * .19, canvasBox.y + canvasBox.height * .34);
  await page.locator("#feltEditor[open]").waitFor();
  if (await page.locator("#feltEditorDelete").isHidden()) throw new Error("delete action is missing for an existing note");
  const beforeDelete = (await page.evaluate(() => JSON.parse(localStorage.getItem("km-felt-canvas-notes-v1") || "[]"))).length;
  await page.locator("#feltEditorDelete").click();
  const afterDelete = (await page.evaluate(() => JSON.parse(localStorage.getItem("km-felt-canvas-notes-v1") || "[]"))).length;
  if (afterDelete !== beforeDelete - 1) throw new Error("editor delete action did not remove one note");
  await page.screenshot({ path: "tests/felt-canvas-v2.png", fullPage: true });
  if (errors.length) throw new Error(errors.join("\n"));
  console.log("FELT_CANVAS_V2_OK"); await browser.close();
})().catch(error => { console.error(error); process.exitCode = 1; });
